import { describe, expect, it } from "@effect/vitest";

import { exportCss, exportFiles, exportTailwind, exportTs, readTokens } from "./tokens.ts";
import { passingTokens } from "./tokens.testkit.ts";

const messages = (document: unknown) => readTokens(document).errors.map((issue) => issue.message);

describe("readTokens", () => {
  it("accepts a complete kit and resolves aliases", () => {
    const report = readTokens(passingTokens());
    expect(report.errors).toEqual([]);
    expect(report.tokens?.color.light.primary).toBe("#1d4ed8");
    expect(report.tokens?.color.dark.focus).toBe("#60a5fa");
    expect(report.tokens?.font.sans).toBe('"Inter Tight", system-ui, sans-serif');
    expect(report.tokens?.space).toEqual({ "0-5": "2px", "1": "4px", "2": "8px" });
    expect(report.tokens?.text.body).toEqual({
      size: "26px",
      lineHeight: "1.4",
      weight: "500",
      tracking: "0",
    });
    expect(report.tokens?.flat["motion.fast"]).toBe("120ms");
    expect(report.contrast).toHaveLength(12);
    expect(report.contrast.every((check) => check.passes)).toBe(true);
  });

  it("reports every missing required role", () => {
    const document = passingTokens();
    const { primary: _primary, ...light } = document.color.light;
    const { h3: _h3, ...roles } = document.typography.role;
    const result = messages({
      ...document,
      color: { ...document.color, light },
      typography: { ...document.typography, role: roles },
      radius: {},
    });
    expect(result).toEqual(
      expect.arrayContaining([
        "color.light.primary is missing.",
        "typography.role.h3 is missing.",
        "radius needs at least one token.",
      ]),
    );
    expect(
      readTokens({ ...document, space: undefined }).errors.map((issue) => issue.message),
    ).toContain("space is missing.");
  });

  it("fails text contrast below 4.5:1 and warns on faint borders", () => {
    const document = passingTokens();
    const report = readTokens({
      ...document,
      color: {
        ...document.color,
        light: {
          ...document.color.light,
          "muted-foreground": { $value: "#9ca3af" },
          border: { $value: "#f3f4f6" },
        },
      },
    });
    expect(report.errors.map((issue) => issue.message)).toEqual([
      "light: muted-foreground on background is 2.54:1; it needs at least 4.5:1.",
    ]);
    expect(report.warnings.map((issue) => issue.message)).toEqual([
      "light: border on background is 1.1:1; it needs at least 1.5:1.",
    ]);
    expect(report.tokens).toBeUndefined();
  });

  it("rejects unreadable colors, broken aliases and values that would escape CSS", () => {
    const document = passingTokens();
    const result = messages({
      ...document,
      color: {
        ...document.color,
        light: {
          ...document.color.light,
          accent: { $value: "tomato" },
          success: { $value: "{color.primitive.green.500}" },
          warning: { $value: "{color.light.danger}" },
          danger: { $value: "{color.light.warning}" },
        },
      },
      typography: {
        ...document.typography,
        family: { sans: { $value: "Inter; } body { display: none" } },
      },
    });
    expect(result).toEqual(
      expect.arrayContaining([
        "color.light.accent is not a color we can read. Use #rrggbb, rgb(r g b) or oklch(L C H).",
        "color.light.success refers to {color.primitive.green.500}, which is not a token.",
        "color.light.warning has an alias cycle through {color.light.danger}.",
        "typography.family.sans contains characters that are not allowed in a CSS value.",
      ]),
    );
  });
});

describe("exports", () => {
  const tokens = readTokens(passingTokens()).tokens!;

  it("writes light, system dark and forced dark color blocks", () => {
    expect(exportCss(tokens)).toMatchSnapshot();
  });

  it("writes Tailwind v4 theme variables", () => {
    const css = exportTailwind(tokens);
    expect(css).toContain("@theme {\n  --color-accent: rgb(190 24 93);");
    expect(css).toContain("  --text-body--line-height: 1.4;");
    expect(css).toContain("  --spacing-0-5: 2px;");
    expect(css).toContain('[data-theme="dark"] {\n  --color-accent: #f472b6;');
  });

  it("writes a typed constant", () => {
    expect(exportTs(tokens)).toMatch(
      /^\/\/ Generated by Moonfold[^\n]*\nexport const tokens = \{\n {2}"color": \{\n {4}"dark": \{/,
    );
    expect(exportTs(tokens)).toContain("} as const;\n\nexport type Tokens = typeof tokens;\n");
  });

  it("gives identical files for the same tokens in any key order", () => {
    const reordered = JSON.parse(
      JSON.stringify(passingTokens(), (_key, value: unknown) =>
        typeof value === "object" && value !== null && !Array.isArray(value)
          ? Object.fromEntries(Object.entries(value).toReversed())
          : value,
      ),
    ) as unknown;
    expect(exportFiles(readTokens(reordered).tokens!)).toEqual(exportFiles(tokens));
  });
});
